/* Defined conversions: avoid implementation-defined uint32_t -> int32_t
 * conversion for words with bit31 set. Byte order is handled before these.
 */
static inline int32_t fpga_abi_word_to_s32(uint32_t word)
{
    return word <= UINT32_C(0x7FFFFFFF) ? (int32_t)word :
           -INT32_C(1) - (int32_t)(UINT32_MAX - word);
}
static inline int32_t fpga_abi_feature_lag(uint32_t word)
{
    uint32_t low = word & FEATURE_0_LAG_MASK;
    return low < UINT32_C(128) ? (int32_t)low : (int32_t)low - INT32_C(256);
}
#define FEATURE_0_GET_LAG(w) fpga_abi_feature_lag((uint32_t)(w))

